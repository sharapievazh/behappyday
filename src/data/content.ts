// Функция получения индекса дня для массива заданной длины
export function getDayIndex(arrayLength: number = AFFIRMATIONS.length): number {
  const startOfYear = new Date(new Date().getFullYear(), 0, 0);
  const diff = Date.now() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / 86400000);
  return dayOfYear % arrayLength;
}
